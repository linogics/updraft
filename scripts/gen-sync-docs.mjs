#!/usr/bin/env node
// Generates the markdown reference of the sync HTTP spec from its OpenAPI file.
//
// Usage: node gen-sync-docs.mjs <openapi.yaml> <reference.md>
import { readFileSync, writeFileSync } from 'node:fs';

import { parse } from 'yaml';

const [file, out] = process.argv.slice(2);
if (!file || !out) {
  console.error('Usage: node gen-sync-docs.mjs <openapi.yaml> <reference.md>');
  process.exit(1);
}

const spec = parse(readFileSync(file, 'utf8'));
const METHODS = ['get', 'put', 'post', 'delete'];

const resolve = (o) => {
  if (!o?.$ref) return o;
  const target = o.$ref
    .slice(2)
    .split('/')
    .reduce((acc, k) => acc[k], spec);
  // A sibling description overrides the referenced one.
  return { ...target, ...(o.description ? { description: o.description } : {}) };
};

const cell = (s) =>
  String(s ?? '')
    .replace(/\|/g, '\\|')
    .replace(/\s*\n\s*/g, ' ')
    .trim();

function typeOf(s) {
  if (!s) return '`any`';

  if (s.$ref) {
    const name = s.$ref.split('/').pop();
    return `[${name}](#${name.toLowerCase()})`;
  }

  if (s.anyOf) return s.anyOf.map(typeOf).join(' or ');
  if (s.const !== undefined) return `\`${JSON.stringify(s.const)}\``;
  if (s.enum) return s.enum.map((e) => `\`${JSON.stringify(e)}\``).join(' or ');
  if (s.type === 'array') return `${typeOf(s.items)}[]`;
  return `\`${s.type ?? 'any'}\`${s.format ? ` (${s.format})` : ''}`;
}

function fields(s) {
  const required = new Set(s.required ?? []);
  const rows = Object.entries(s.properties ?? {}).map(
    ([name, p]) => `| \`${name}\` | ${typeOf(p)} | ${required.has(name) ? 'yes' : 'no'} | ${cell(p.description)} |`
  );
  if (!rows.length) return '';
  return ['| Field | Type | Required | Description |', '| --- | --- | --- | --- |', ...rows, ''].join('\n');
}

function body(content) {
  return Object.entries(content ?? {})
    .map(([type, c]) => `\`${type}\`: ${typeOf(c.schema)}`)
    .join('\n\n');
}

function operation(path, method, op, shared) {
  const lines = [`## ${method.toUpperCase()} ${path}`, '', `**${op.summary}** (\`${op.operationId}\`)`, ''];
  if (op.description) lines.push(op.description.trim(), '');
  if (op.security?.length === 0) lines.push('No token needed.', '');

  const params = [...(shared ?? []), ...(op.parameters ?? [])].map(resolve);
  if (params.length) {
    lines.push('| Parameter | In | Required | Type | Description |', '| --- | --- | --- | --- | --- |');
    for (const p of params) {
      const req = p.required ? 'yes' : 'no';
      lines.push(`| \`${p.name}\` | ${p.in} | ${req} | ${typeOf(p.schema)} | ${cell(p.description)} |`);
    }

    lines.push('');
  }

  if (op.requestBody) lines.push('Request body: ' + body(resolve(op.requestBody).content), '');

  lines.push('| Status | Description | Body |', '| --- | --- | --- |');
  for (const [status, raw] of Object.entries(op.responses)) {
    const r = resolve(raw);
    const headers = Object.keys(r.headers ?? {}).map((h) => `\`${h}\``);
    const desc = cell(r.description) + (headers.length ? ` Headers: ${headers.join(', ')}.` : '');
    lines.push(`| ${status} | ${desc} | ${cell(body(r.content)) || 'none'} |`);
  }

  lines.push('');
  return lines.join('\n');
}

const parts = [
  '<!-- Generated by scripts/gen-sync-docs.mjs from openapi.yaml. Do not edit. -->',
  '',
  `# ${spec.info.title}, reference`,
  '',
  'Generated from [openapi.yaml](openapi.yaml). The [guide](README.md) explains the reasons.',
  '',
  `Base path: \`${spec.servers[0].url}\`. Paths below are relative to it. Every route needs \`Authorization: Bearer <token>\` unless it says otherwise.`,
  '',
  '# Operations',
  ''
];

for (const [path, item] of Object.entries(spec.paths)) {
  for (const method of METHODS) {
    if (item[method]) parts.push(operation(path, method, item[method], item.parameters));
  }
}

parts.push('# Schemas', '');
for (const [name, s] of Object.entries(spec.components.schemas)) {
  parts.push(`## ${name}`, '');
  if (s.description) parts.push(s.description.trim(), '');
  const table = fields(s);
  if (table) parts.push(table);
  else parts.push(`Type: ${typeOf(s)}`, '');
}

writeFileSync(out, parts.join('\n').replace(/\n+$/, '\n'));
